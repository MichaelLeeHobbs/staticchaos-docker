#!/usr/bin/env node
/*
 * build-bestiary.mjs -- Static Chaos bestiary (mobiles).
 *
 * Parses every area's #MOBILES section and emits, under world-maps/:
 *   bestiary.json   every mob: name, keywords, level, behaviour flags, area
 *   BESTIARY.md     a printable bestiary grouped by area, a level-band
 *                   summary, and a "biggest threats" table (highest level).
 *
 * Usage:  node tools/build-bestiary.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseAreaFile, loadAreaList, cell, actList } from './lib/area.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const AREA_DIR = path.join(ROOT, 'area');
const OUT = path.join(ROOT, 'world-maps');

const band = (lvl) => (lvl >= 90 ? '90+' : lvl >= 70 ? '70–89' : lvl >= 50 ? '50–69' : lvl >= 30 ? '30–49' : lvl >= 10 ? '10–29' : '1–9');

function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const areas = [];
  const all = [];
  for (const f of loadAreaList(AREA_DIR)) {
    const a = parseAreaFile(path.join(AREA_DIR, f));
    if (!a.mobiles.length) continue;
    areas.push({ id: a.id, name: a.name, mobiles: a.mobiles });
    for (const m of a.mobiles) all.push({ ...m, area: a.id, areaName: a.name });
  }

  // ---- json ----
  const bands = {};
  for (const m of all) bands[band(m.level)] = (bands[band(m.level)] || 0) + 1;
  const data = {
    stats: { totalMobs: all.length, areas: areas.length, byLevelBand: bands },
    mobs: all.map((m) => ({ vnum: m.vnum, name: m.name, keywords: m.keywords, level: m.level, behaviour: actList(m.act), area: m.area, sighting: m.long })),
  };
  fs.writeFileSync(path.join(OUT, 'bestiary.json'), JSON.stringify(data, null, 2) + '\n');

  // ---- markdown ----
  const out = [];
  out.push('# Static Chaos -- Bestiary', '');
  out.push('> Generated by `tools/build-bestiary.mjs` from the area files. Do not edit by hand.', '');
  out.push('## At a glance', '', `**${all.length}** creatures across **${areas.length}** areas.`, '');
  out.push('| Level band | Count |', '|---|---:|');
  for (const b of ['1–9', '10–29', '30–49', '50–69', '70–89', '90+']) if (bands[b]) out.push(`| ${b} | ${bands[b]} |`);
  out.push('');

  // biggest threats
  const threats = [...all].sort((a, b) => b.level - a.level).slice(0, 50);
  out.push('## Biggest threats (highest level)', '', 'Top 50 by level.', '');
  out.push('| VNUM | Creature | Lvl | Behaviour | Area |', '|---:|---|---:|---|---|');
  for (const m of threats) out.push(`| ${m.vnum} | ${cell(m.name)} | ${m.level} | ${actList(m.act).join(', ') || '—'} | ${m.area} |`);
  out.push('');

  // full bestiary by area
  out.push('## Full bestiary by area', '');
  for (const a of areas.sort((x, y) => x.id.localeCompare(y.id))) {
    out.push(`### ${a.name}  \`(${a.id})\``, '', `${a.mobiles.length} creatures`, '');
    out.push('| VNUM | Creature | Lvl | Behaviour | Where you see it |', '|---:|---|---:|---|---|');
    for (const m of a.mobiles.sort((x, y) => y.level - x.level)) {
      out.push(`| ${m.vnum} | ${cell(m.name)} | ${m.level} | ${actList(m.act).join(', ') || '—'} | ${cell(m.long)} |`);
    }
    out.push('');
  }
  fs.writeFileSync(path.join(OUT, 'BESTIARY.md'), out.join('\n') + '\n');

  console.log(`bestiary : ${all.length} mobs across ${areas.length} areas`);
  console.log(`           -> world-maps/{bestiary.json, BESTIARY.md}`);
}
main();

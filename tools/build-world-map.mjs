#!/usr/bin/env node
/*
 * build-world-map.mjs -- Static Chaos world cartographer.
 *
 * Parses every live area's #ROOMDATA into a directed room graph and emits,
 * all under world-maps/:
 *   world.json         canonical graph + analysis reports
 *   WORLD-MAP.md       stats, area-connectivity Mermaid, area index, reports
 *   <area>.md          one Mermaid room graph + room table per area
 *   WORLD-ATLAS.md     print-friendly (no Mermaid) atlas -> feeds the PDF
 *
 * Usage:  node tools/build-world-map.mjs   (run from the project root)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseAreaFile, loadAreaList, mlabel, cell, DIR_WORD } from './lib/area.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const AREA_DIR = path.join(ROOT, 'area');
const OUT = path.join(ROOT, 'world-maps');

const RECALL_VNUM = 3001; // Temple of Midgaard -- the recall point.

/* ------------------------------------------------------------------ */
function build() {
  const areas = [];
  const rooms = new Map();
  const vnumToArea = new Map();

  for (const f of loadAreaList(AREA_DIR)) {
    const a = parseAreaFile(path.join(AREA_DIR, f));
    if (!a.rooms.length) continue;
    const vnums = a.rooms.map((r) => r.vnum);
    areas.push({ id: a.id, file: a.file, name: a.name, roomCount: a.rooms.length, vnumMin: Math.min(...vnums), vnumMax: Math.max(...vnums) });
    for (const room of a.rooms) { room.area = a.id; rooms.set(room.vnum, room); vnumToArea.set(room.vnum, a.id); }
  }

  const dangling = [], oneWay = [], crossArea = [];
  let exitCount = 0;
  const inbound = new Map();
  for (const room of rooms.values()) {
    for (const [dir, to] of Object.entries(room.exits)) {
      exitCount++;
      const dest = rooms.get(to);
      if (!dest) { dangling.push({ from: room.vnum, dir, to }); continue; }
      inbound.set(to, (inbound.get(to) || 0) + 1);
      if (!Object.values(dest.exits).includes(room.vnum)) oneWay.push({ from: room.vnum, dir, to });
      if (dest.area !== room.area) crossArea.push({ fromArea: room.area, toArea: dest.area, from: room.vnum, to, dir });
    }
  }
  const orphans = [...rooms.values()].filter((r) => !inbound.has(r.vnum)).map((r) => r.vnum);

  // reachability BFS from the recall point
  const reachable = new Set();
  if (rooms.has(RECALL_VNUM)) {
    const q = [RECALL_VNUM]; reachable.add(RECALL_VNUM);
    while (q.length) {
      const room = rooms.get(q.shift());
      if (!room) continue;
      for (const to of Object.values(room.exits)) if (rooms.has(to) && !reachable.has(to)) { reachable.add(to); q.push(to); }
    }
  }
  const reachableByArea = new Map();
  for (const v of reachable) reachableByArea.set(vnumToArea.get(v), (reachableByArea.get(vnumToArea.get(v)) || 0) + 1);
  const unreachableAreas = areas.filter((a) => !(reachableByArea.get(a.id) > 0)).map((a) => a.id);

  const inboundAreas = new Map();
  for (const e of crossArea) { if (!inboundAreas.has(e.toArea)) inboundAreas.set(e.toArea, new Set()); inboundAreas.get(e.toArea).add(e.fromArea); }

  areas.sort((a, b) => a.vnumMin - b.vnumMin);
  const world = {
    generatedFrom: 'area/area.lst', recallVnum: RECALL_VNUM,
    stats: {
      areas: areas.length, rooms: rooms.size, exits: exitCount, crossAreaLinks: crossArea.length,
      danglingExits: dangling.length, oneWayExits: oneWay.length, orphanRooms: orphans.length,
      reachableFromRecall: reachable.size, unreachableRooms: rooms.size - reachable.size, unreachableAreas: unreachableAreas.length,
    },
    areas,
    rooms: Object.fromEntries([...rooms.entries()].sort((a, b) => a[0] - b[0])
      .map(([v, r]) => [v, { vnum: r.vnum, name: r.name, area: r.area, sector: r.sector, exits: r.exits }])),
    reports: { unreachableAreas, orphanRooms: orphans.sort((a, b) => a - b), danglingExits: dangling, oneWayExits: oneWay, crossAreaLinks: crossArea },
  };
  return { world, rooms, areas, crossArea, reachableByArea, inboundAreas };
}

/* ------------------------------------------------------------------ */
function areaOverviewMermaid(areas, crossArea) {
  const pair = new Map();
  for (const e of crossArea) { if (e.fromArea === e.toArea) continue; const k = `${e.fromArea}${e.toArea}`; pair.set(k, (pair.get(k) || 0) + 1); }
  const lines = ['graph LR'];
  for (const a of areas) lines.push(`  ${a.id}["${mlabel(a.name)}"]`);
  for (const [k, count] of pair) { const [from, to] = k.split(''); lines.push(count > 1 ? `  ${from} -->|${count}| ${to}` : `  ${from} --> ${to}`); }
  return lines.join('\n');
}

function writeOverview(world, areas, crossArea, reachableByArea, inboundAreas) {
  const s = world.stats; const out = [];
  out.push('# Static Chaos -- World Map', '');
  out.push('> Generated by `tools/build-world-map.mjs` from `area/area.lst`. Do not edit by hand.', '');
  out.push('## At a glance', '', '| Metric | Value |', '|---|---:|');
  out.push(`| Areas | ${s.areas} |`, `| Rooms | ${s.rooms} |`, `| Exits | ${s.exits} |`, `| Cross-area links | ${s.crossAreaLinks} |`);
  out.push(`| Reachable from recall (Temple, #${world.recallVnum}) | ${s.reachableFromRecall} |`);
  out.push(`| **Unreachable rooms** | ${s.unreachableRooms} |`, `| **Unreachable areas** | ${s.unreachableAreas} |`);
  out.push(`| One-way exits | ${s.oneWayExits} |`, `| Dangling exits (broken) | ${s.danglingExits} |`, `| Orphan rooms (no way in) | ${s.orphanRooms} |`, '');
  out.push('## World overview (area connectivity)', '');
  out.push('Each node is an area; an arrow means at least one room in the source area has an exit into the target area. A number on the arrow is how many such links exist.', '');
  out.push('```mermaid', areaOverviewMermaid(areas, crossArea), '```', '');
  out.push('## Areas', '', '| Area | Name | Rooms | VNUMs | Reachable? | Reached from |', '|---|---|---:|---|:---:|---|');
  for (const a of areas) {
    const reach = reachableByArea.get(a.id) || 0;
    const into = [...(inboundAreas.get(a.id) || [])].sort().join(', ') || '—';
    out.push(`| [\`${a.id}\`](${a.id}.md) | ${cell(a.name)} | ${a.roomCount} | ${a.vnumMin}–${a.vnumMax} | ${reach > 0 ? `✅ ${reach}/${a.roomCount}` : '❌ 0'} | ${into} |`);
  }
  out.push('');
  if (world.reports.unreachableAreas.length) {
    out.push('## ⚠️ Unreachable areas', '');
    out.push(`These areas have **no path from the recall point** (Temple of Midgaard, room ${world.recallVnum}) by walking exits. They exist in the world data, but a mortal cannot reach them on foot — an immortal must \`goto\` a room inside.`, '');
    for (const id of world.reports.unreachableAreas) {
      const a = areas.find((x) => x.id === id);
      const into = [...(inboundAreas.get(id) || [])].sort().join(', ');
      out.push(`- **${cell(a.name)}** (\`${id}\`, rooms ${a.vnumMin}–${a.vnumMax})${into ? ` — only linked from: ${into}` : ' — no inbound links at all'}`);
    }
    out.push('');
  }
  if (world.reports.danglingExits.length) {
    out.push('## Dangling exits (point at rooms that do not exist)', '', '| From | Dir | Missing target |', '|---:|:--:|---:|');
    for (const e of world.reports.danglingExits.slice(0, 200)) out.push(`| ${e.from} | ${e.dir} | ${e.to} |`);
    if (world.reports.danglingExits.length > 200) out.push(`| … | | ${world.reports.danglingExits.length - 200} more |`);
    out.push('');
  }
  fs.writeFileSync(path.join(OUT, 'WORLD-MAP.md'), out.join('\n') + '\n');
}

function areaMermaid(area, rooms) {
  const inArea = [...rooms.values()].filter((r) => r.area === area.id);
  const lines = ['graph LR'];
  for (const r of inArea) lines.push(`  R${r.vnum}["${mlabel(r.name)}<br/>#${r.vnum}"]`);
  const ext = new Map();
  for (const r of inArea) for (const [dir, to] of Object.entries(r.exits)) {
    const dest = rooms.get(to);
    if (dest && dest.area === area.id) { lines.push(`  R${r.vnum} -->|${dir}| R${to}`); }
    else { ext.set(to, dest ? `${mlabel(dest.name)}<br/>${dest.area} #${to}` : `?? broken<br/>#${to}`); lines.push(`  R${r.vnum} -->|${dir}| X${to}`); }
  }
  for (const [to, label] of ext) lines.push(`  X${to}["${label}"]:::ext`);
  lines.push('  classDef ext fill:#222,stroke:#888,color:#bbb,stroke-dasharray:3 3;');
  return lines.join('\n');
}

function writeAreaPages(areas, rooms) {
  for (const a of areas) {
    const inArea = [...rooms.values()].filter((r) => r.area === a.id).sort((x, y) => x.vnum - y.vnum);
    const out = [];
    out.push(`# ${a.name}  \`(${a.id})\``, '');
    out.push(`[← back to world map](WORLD-MAP.md) · ${inArea.length} rooms · vnums ${a.vnumMin}–${a.vnumMax}`, '');
    out.push('Dashed nodes are exits that leave this area.', '');
    out.push('```mermaid', areaMermaid(a, rooms), '```', '');
    out.push('## Rooms', '', '| VNUM | Name | Exits |', '|---:|---|---|');
    for (const r of inArea) {
      const ex = Object.entries(r.exits).map(([d, to]) => `${d}→${to}`).join(' ') || '—';
      out.push(`| ${r.vnum} | ${cell(r.name) || '(unnamed)'} | ${ex} |`);
    }
    out.push('');
    fs.writeFileSync(path.join(OUT, `${a.id}.md`), out.join('\n') + '\n');
  }
}

// print-friendly atlas (no Mermaid) -> PDF source
function writeAtlas(world, areas, rooms, reachableByArea) {
  const s = world.stats; const out = [];
  out.push('# Static Chaos -- World Atlas', '');
  out.push('_A printable reference of every area, room and exit. Generated from the live area files._', '');
  out.push(`**${s.areas}** areas · **${s.rooms}** rooms · **${s.exits}** exits · **${s.crossAreaLinks}** cross-area links`, '');
  for (const a of areas) {
    const inArea = [...rooms.values()].filter((r) => r.area === a.id).sort((x, y) => x.vnum - y.vnum);
    const reach = reachableByArea.get(a.id) || 0;
    out.push('<div style="page-break-before: always"></div>', '');
    out.push(`## ${a.name}`, '');
    out.push(`\`${a.id}\` · ${inArea.length} rooms · vnums ${a.vnumMin}–${a.vnumMax} · ${reach > 0 ? 'reachable from town' : 'NOT reachable from town'}`, '');
    out.push('| VNUM | Room | Exits |', '|---:|---|---|');
    for (const r of inArea) {
      const ex = Object.entries(r.exits).map(([d, to]) => `${DIR_WORD[d]}→${to}`).join(', ') || '—';
      out.push(`| ${r.vnum} | ${cell(r.name) || '(unnamed)'} | ${ex} |`);
    }
    out.push('');
  }
  fs.writeFileSync(path.join(OUT, 'WORLD-ATLAS.md'), out.join('\n') + '\n');
}

/* ------------------------------------------------------------------ */
function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const { world, rooms, areas, crossArea, reachableByArea, inboundAreas } = build();
  fs.writeFileSync(path.join(OUT, 'world.json'), JSON.stringify(world, null, 2) + '\n');
  writeOverview(world, areas, crossArea, reachableByArea, inboundAreas);
  writeAreaPages(areas, rooms);
  writeAtlas(world, areas, rooms, reachableByArea);
  const s = world.stats;
  console.log(`world : ${s.areas} areas, ${s.rooms} rooms, ${s.exits} exits, ${s.crossAreaLinks} cross-area links`);
  console.log(`        reachable ${s.reachableFromRecall}, unreachable ${s.unreachableRooms} rooms / ${s.unreachableAreas} areas (${world.reports.unreachableAreas.join(', ') || 'none'})`);
  console.log(`        -> world-maps/{world.json, WORLD-MAP.md, <area>.md, WORLD-ATLAS.md}`);
}
main();
